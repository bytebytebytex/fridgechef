export function getProductName(key: string, lang: Lang): string {
  const product = PRODUCT_NAMES[key];
  if (product) return product[lang];
  // Capitalize first letter for unknown products
  return key.charAt(0).toUpperCase() + key.slice(1);
}

export function getProductEmoji(key: string): string {
  const product = PRODUCT_NAMES[key];
  return product?.emoji || "🥘";
}
